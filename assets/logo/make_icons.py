"""Renders the Statlet logo (statlet-template.svg's geometry) with PIL: statlet-app.ico/png, tray-dark/light.ico,
and island/src/tray_masks.h (alpha masks the island tints with the accent at runtime). Run: python make_icons.py"""
import io, math, os, struct
from PIL import Image, ImageDraw, ImageChops

HERE = os.path.dirname(os.path.abspath(__file__))
SKY = (0x38, 0xBD, 0xF8)
INK_LIGHT_TASKBAR = (0x1B, 0x1F, 0x27)
M = 1024  # master raster; 4 px per SVG unit

def stroke(points, w=36):
    m = Image.new("L", (M, M), 0)
    d = ImageDraw.Draw(m)
    r = w / 2 * M / 256
    for x, y in points:
        x, y = x * M / 256, (y + 3) * M / 256
        d.ellipse((x - r, y - r, x + r, y + r), fill=255)
    return m

def line(x0, x1, y, n=200):
    return [(x0 + (x1 - x0) * i / n, y) for i in range(n + 1)]

def arc(cx, cy, r, a0, a1, n=120):
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)), cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]

pill = stroke(line(118, 184, 66))
s_path = stroke(arc(100, 100, 28, 150, 90) + line(100, 156, 128) + arc(156, 156, 28, -90, 90) + line(156, 72, 184))

def tint(mask, rgb):
    return Image.merge("RGBA", (*[Image.new("L", mask.size, c) for c in rgb], mask))

def glyph(accent, ink):
    g = tint(s_path, ink)
    g.alpha_composite(tint(pill, accent))
    return g

def tile(accent):
    k = M / 256
    def rr(box, r):
        m = Image.new("L", (M, M), 0)
        ImageDraw.Draw(m).rounded_rectangle([v * k for v in box], r * k, fill=255)
        return m
    grad = Image.new("RGBA", (M, M))
    gd = ImageDraw.Draw(grad)
    for y in range(M):
        t = y / (M - 1)
        gd.line((0, y, M, y), fill=tuple(round(a + (b - a) * t) for a, b in zip((0x2A, 0x2E, 0x37), (0x12, 0x14, 0x18))) + (255,))
    base = Image.new("RGBA", (M, M), (0, 0, 0, 0))
    base.paste(grad, mask=rr((8, 8, 248, 248), 56))
    ring = ImageChops.subtract(rr((8, 8, 248, 248), 56), rr((12, 12, 244, 244), 52))
    base.alpha_composite(tint(ring.point(lambda v: v * 0.12), (255, 255, 255)))
    base.alpha_composite(glyph(accent, (255, 255, 255)))
    return base

def trayCrop(img):  # glyph only, cropped square around its bounds, with a small margin
    return img.crop((int(52 * 4), int(48 * 4), int(212 * 4), int(208 * 4)))

def ico(frames, path):
    blobs = []
    for im in frames:
        b = io.BytesIO(); im.save(b, "PNG"); blobs.append((im.width, b.getvalue()))
    out = struct.pack("<HHH", 0, 1, len(blobs)); off = 6 + 16 * len(blobs)
    for w, d in blobs:
        out += struct.pack("<BBBBHHII", w % 256, w % 256, 0, 0, 1, 32, len(d), off); off += len(d)
    open(path, "wb").write(out + b"".join(d for _, d in blobs))

def sized(img, n): return img.resize((n, n), Image.LANCZOS)

app = tile(SKY)
ico([sized(app, n) for n in (16, 20, 24, 32, 40, 48, 64, 128, 256)], os.path.join(HERE, "statlet-app.ico"))
sized(app, 64).save(os.path.join(HERE, "statlet-app.png"))
ico_sizes = (16, 20, 24, 32, 48)
for name, ink in (("dark", (255, 255, 255)), ("light", INK_LIGHT_TASKBAR)):
    g = trayCrop(glyph(SKY, ink))
    ico([sized(g, n) for n in ico_sizes], os.path.join(HERE, f"tray-{name}.ico"))

# Alpha masks (S, pill) per tray size for runtime tinting.
masks = [(n, sized(trayCrop(tint(s_path, (0, 0, 0))), n).getchannel("A"), sized(trayCrop(tint(pill, (0, 0, 0))), n).getchannel("A")) for n in ico_sizes]
hdr = os.path.join(HERE, "..", "..", "island", "src", "tray_masks.h")
with open(hdr, "w") as f:
    f.write("// Generated by assets/logo/make_icons.py: tray glyph alpha masks (S, accent pill) per icon size.\n#pragma once\n#include <cstdint>\n\n")
    f.write("struct TrayMask { int size; const uint8_t* s; const uint8_t* pill; };\n")
    for n, s, p in masks:
        for tag, m in (("s", s), ("p", p)):
            f.write(f"static const uint8_t tray{tag}{n}[] = {{{','.join(map(str, m.tobytes()))}}};\n")
    f.write("static const TrayMask trayMasks[] = {" + ",".join(f"{{{n},trays{n},trayp{n}}}" for n, *_ in masks) + "};\n")
